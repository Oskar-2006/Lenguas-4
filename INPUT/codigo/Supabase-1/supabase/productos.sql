-- ============================================================
-- se pega entero en el SQL Editor de Supabase y se ejecuta una sola vez.
-- es la version "real" de productos_practica: mismas columnas que la
-- semana 11 (guia_relaciones_claves_supabase, seccion 2), sin "_practica"
-- porque es para el proyecto final. queda vacia: los productos se agregan
-- desde admin.html.

-- 1) LA TABLA
-- id se autogenera (1, 2, 3...), igual que en productos_practica.
-- categorias es una lista (json), como en productos_practica: ["sillas", "pc"].
-- plataforma es nueva: sale de la ficha de Solo Juega (PC, consola o ambas).
create table public.productos (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    nombre text not null,
    descripcion text,
    precio int8 not null default 0 check (precio >= 0),
    unidades int8 not null default 0 check (unidades >= 0),
    descuento int8 not null default 0 check (descuento >= 0),
    disponible boolean not null default true,
    categorias json default '[]',
    plataforma text check (plataforma in ('PC', 'Consola', 'Ambas')),
    image_url text
);

-- 2) SIN RLS
-- igual que clientes: por ahora RLS va desactivado (decision del 30/10).
-- cuando se active, hay que crear las politicas de la guia del panel de
-- administrador (solo admin crea, edita y elimina).
alter table public.productos disable row level security;
