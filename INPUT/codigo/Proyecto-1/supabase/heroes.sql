-- 1) LA TABLA
-- una columna por cada propiedad de los objetos de data.js. los nombres
-- con mayuscula van entre comillas: sin comillas Postgres los pasa a
-- minusculas ("colorPrincipal" quedaria colorprincipal) y el JS ya no los
-- encontraria con heroe.colorPrincipal.
-- "orden" es nueva: en localStorage el orden era la posicion en el array,
-- pero una tabla no tiene orden propio. hay que guardarlo en una columna.
create table public.heroes (
    id bigint generated by default as identity primary key,
    orden int not null default 0,
    nombre text not null,
    imagen text,
    "imagenFondoBlanco" boolean default false,
    edad int8,
    poderes json default '[]',
    descripcion text,
    bando text,
    universo text,
    niveldefuerza int8,
    activo boolean default true,
    "colorPrincipal" text,
    "colorSecundario" text,
    created_at timestamptz default now()
);

