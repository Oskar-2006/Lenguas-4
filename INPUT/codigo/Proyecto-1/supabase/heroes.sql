-- 3) PERMISOS TEMPORALES (seccion 3.4 de la guia, opcion B)
-- RLS activo con una politica abierta: cualquiera puede leer y escribir.
-- sirve para practicar el CRUD; en la semana 13 (Auth) se reemplaza por
-- reglas reales
alter table public.heroes enable row level security;

create policy "heroes: acceso abierto temporal"
    on public.heroes for all
    to anon
    using (true)
    with check (true);

-- 4) STORAGE PARA LAS IMAGENES
-- un bucket es una carpeta de archivos en Supabase. "public = true" hace
-- que cada imagen tenga una URL que se puede poner en un <img> sin permiso
insert into storage.buckets (id, name, public)
values ('heroes', 'heroes', true);

-- el bucket tiene sus PROPIOS permisos, separados de los de la tabla.
-- esta politica deja subir archivos (insert) solo dentro de este bucket
create policy "heroes imagenes: subir (temporal)"
    on storage.objects for insert
    to anon
    with check (bucket_id = 'heroes');
